from sklearn.preprocessing import StandardScaler, LabelEncoder
from sklearn.impute import SimpleImputer

class AgenteNormalizador:
    """
    Agente 1 – Normalizador
    Usa el LLM para analizar el dataset y describir la estrategia,
    luego ejecuta: limpieza → imputación → codificación → escalado.
    """

    def __init__(self, llm_fn, target='recovery_days'):
        self.llm                  = llm_fn
        self.target               = target
        self.scaler               = StandardScaler()
        self.label_encoders       = {}
        self.imputer_num          = SimpleImputer(strategy='median')
        self.imputer_cat          = SimpleImputer(strategy='most_frequent')
        self.log                  = []
        self.columnas_numericas   = []
        self.columnas_categoricas = []

    # ── LLM: analiza el dataset y sugiere estrategia ──────
    def analizar_con_llm(self, df):
        resumen = (
            f"Dataset columns: {list(df.columns)}. "
            f"Rows: {len(df)}. "
            f"Null values per column: {df.isnull().sum().to_dict()}. "
            f"Duplicate rows: {df.duplicated().sum()}. "
            f"Target variable: {self.target}. "
            f"Suggest a data cleaning and preprocessing strategy for this drug side effects dataset."
        )
        respuesta = self.llm(resumen)
        print('\n🤖 LLM – Estrategia de normalización sugerida:')
        print(f'   "{respuesta}"\n')
        self.log.append(f'🤖 LLM estrategia: {respuesta}')

    # ── PASO 1: Limpieza ──────────────────────────────────
    def limpiar(self, df):
        n0 = len(df)
        # Eliminar duplicados
        df = df.drop_duplicates().reset_index(drop=True)
        # Eliminar columnas no útiles para el modelo
        cols_drop = ['patient_id', 'report_date', 'treatment_start_date']
        df = df.drop(columns=[c for c in cols_drop if c in df.columns])
        # Eliminar filas sin target
        df = df.dropna(subset=[self.target])
        # Filtrar valores raros en target
        df = df[df[self.target] >= 0]
        self.log.append(f'🗑️  Duplicados eliminados    : {n0 - len(df)}')
        self.log.append(f'🔍 Filas tras limpieza       : {len(df)} (inicio: {n0})')
        return df.reset_index(drop=True)

    # ── PASO 2: Clasificar columnas ───────────────────────
    def clasificar_columnas(self, df):
        self.columnas_categoricas = df.select_dtypes(include=['object']).columns.tolist()
        self.columnas_numericas   = [
            c for c in df.select_dtypes(include=[np.number]).columns
            if c != self.target
        ]
        self.log.append(f'📌 Numéricas  ({len(self.columnas_numericas)})   : {self.columnas_numericas}')
        self.log.append(f'🏷️  Categóricas({len(self.columnas_categoricas)})   : {self.columnas_categoricas}')
        return df

    # ── PASO 3: Imputación ────────────────────────────────
    def imputar(self, df):
        nulos_antes = df.isnull().sum().sum()
        if self.columnas_numericas:
            df[self.columnas_numericas] = self.imputer_num.fit_transform(df[self.columnas_numericas])
        if self.columnas_categoricas:
            # Use .values.reshape(-1, 1) to ensure 2D array for imputer
            df[self.columnas_categoricas] = self.imputer_cat.fit_transform(df[self.columnas_categoricas])
        self.log.append(f'🩹 Imputación: {nulos_antes} nulos → {df.isnull().sum().sum()} nulos')
        return df

    # ── PASO 4: Codificación ──────────────────────────────
    def codificar(self, df):
        for col in self.columnas_categoricas:
            le = LabelEncoder()
            df[col] = le.fit_transform(df[col].astype(str))
            self.label_encoders[col] = le
        self.log.append(f'🔢 LabelEncoder aplicado     : {self.columnas_categoricas}')
        return df

    # ── PASO 5: Escalado ──────────────────────────────────
    def escalar(self, df):
        if self.columnas_numericas:
            df[self.columnas_numericas] = self.scaler.fit_transform(df[self.columnas_numericas])
        self.log.append(f'⚖️  StandardScaler aplicado  : {len(self.columnas_numericas)} columnas')
        return df

    # ── Pipeline completo ─────────────────────────────────
    def ejecutar(self, csv_path):
        print('═'*55)
        print('  🧹 AGENTE 1 – NORMALIZADOR')
        print('═'*55)
        df = pd.read_csv(csv_path)
        self.log.append(f'📥 CSV cargado               : {len(df)} filas')

        self.analizar_con_llm(df)   # ← LLM analiza y sugiere

        df = self.limpiar(df)
        df = self.clasificar_columnas(df)
        df = self.imputar(df)
        df = self.codificar(df)
        df = self.escalar(df)

        df.to_csv('drug_side_effects_clean.csv', index=False)
        self.log.append(f'💾 CSV limpio guardado       : drug_side_effects_clean.csv ({len(df)} filas)')

        print('\n'.join(self.log))
        print('\n✅ Agente 1 finalizado.')
        return df, self.log

