import textwrap

class AgenteComunicador:
    """
    Agente 3 – Comunicador
    Usa el LLM para generar cada sección del reporte
    en lenguaje natural a partir de los resultados del pipeline.
    """

    def __init__(self, llm_fn, modelo_nombre):
        self.llm    = llm_fn
        self.nombre = modelo_nombre

    def _seccion(self, titulo, prompt):
        """Llama al LLM y muestra progreso."""
        print(f'  ✍️  Generando: {titulo}...')
        texto = self.llm(prompt)
        return texto

    # ── Sección 1 ─────────────────────────────────────────
    def s_dataset(self, n_raw, n_clean, n_cols):
        return self._seccion('Descripción del dataset',
            f"Describe a drug side effects dataset used for machine learning. "
            f"It originally had {n_raw} rows. After cleaning it has {n_clean} rows "
            f"and {n_cols} features. Target: recovery_days (number of days to recover).")

    # ── Sección 2 ─────────────────────────────────────────
    def s_preprocesamiento(self, log):
        pasos = '; '.join([e for e in log if not e.startswith('🤖')])
        return self._seccion('Preprocesamiento',
            f"Summarize in plain language the following data preprocessing pipeline log: {pasos}")

    # ── Sección 3 ─────────────────────────────────────────
    def s_comparativa(self, todos, decision_llm):
        comp = ' | '.join([f"{n}: R2={r['test_R2']}, MAE={r['test_MAE']}" for n, r in todos.items()])
        return self._seccion('Comparativa de modelos',
            f"The following models were trained on a drug side effects dataset: {comp}. "
            f"Prior recommendation was: {decision_llm}. "
            f"Summarize the comparison and explain which model performed best.")

    # ── Sección 4 ─────────────────────────────────────────
    def s_metricas(self, nombre, r2, mae, rmse, cv_r2):
        return self._seccion('Interpretación de métricas',
            f"Interpret these regression metrics for the best model ({nombre}) "
            f"predicting recovery days in drug patients: R2={r2}, MAE={mae}, RMSE={rmse}, CV_R2={cv_r2}. "
            f"Explain what each metric means in practical medical terms.")

    # ── Sección 5 ─────────────────────────────────────────
    def s_conclusion(self, nombre, r2, explicacion_llm):
        return self._seccion('Conclusiones y recomendaciones',
            f"Write a conclusion for a machine learning project predicting drug recovery days. "
            f"Best model: {nombre}, R2={r2}. Context: {explicacion_llm}. "
            f"Give two concrete recommendations to improve future performance.")

    # ── Imprimir reporte ──────────────────────────────────
    def imprimir(self, secciones_dict):
        sep = '═' * 62
        lin = '─' * 62
        iconos = {
            'Descripción del dataset'         : '📊',
            'Preprocesamiento'                : '🧹',
            'Comparativa de modelos'          : '🏆',
            'Interpretación de métricas'      : '📈',
            'Conclusiones y recomendaciones'  : '💡'
        }
        print('\n' + sep)
        print('         📋  REPORTE FINAL – PIPELINE ML MULTI-AGENTE')
        print(sep)
        print(f'  LLM utilizado : {self.nombre}')
        print(f'  Framework     : HuggingFace Transformers')
        print(lin)
        for titulo, texto in secciones_dict.items():
            ic = iconos.get(titulo, '📌')
            print(f'\n{ic}  {titulo.upper()}')
            print(lin)
            print(textwrap.fill(texto, width=60,
                                initial_indent='  ', subsequent_indent='  '))
        print('\n' + sep)
        print('  ✅  Reporte generado íntegramente por el LLM (Agente 3)')
        print(sep)

    # ── Pipeline completo ─────────────────────────────────
    def ejecutar(self, log_norm, mejor_nombre, metricas, todos,
                 decision_llm, explicacion_llm, n_raw, n_clean, n_cols):
        print('═'*55)
        print('  📝 AGENTE 3 – COMUNICADOR')
        print('═'*55)
        print('Generando reporte con LLM (5 secciones)...\n')

        secciones = {}
        secciones['Descripción del dataset']        = self.s_dataset(n_raw, n_clean, n_cols)
        secciones['Preprocesamiento']               = self.s_preprocesamiento(log_norm)
        secciones['Comparativa de modelos']         = self.s_comparativa(todos, decision_llm)
        secciones['Interpretación de métricas']     = self.s_metricas(
            mejor_nombre,
            metricas['test_R2'], metricas['test_MAE'],
            metricas['test_RMSE'], metricas['cv_r2_mean']
        )
        secciones['Conclusiones y recomendaciones'] = self.s_conclusion(
            mejor_nombre, metricas['test_R2'], explicacion_llm
        )

        self.imprimir(secciones)
        print('\n✅ Agente 3 finalizado.')
        return secciones

